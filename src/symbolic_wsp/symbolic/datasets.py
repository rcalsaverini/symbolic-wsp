"""Template-disjoint development/validation task generation.
Final tasks are generated by a separate evaluator account with a private seed.
"""

import hashlib
import json

import numpy as np

from .evaluator import evaluate

TEMPLATES = {
    "dev": [
        ("polynomial", "{a}*x+{b}"),
        ("trig", "sin({a}*x)"),
        ("exponential", "exp(x/{a})"),
        ("rational", "1/(x*x+{a})"),
        ("composition", "sin(x)+{a}*x"),
    ],
    "validation": [
        ("polynomial", "{a}*x*x+{b}"),
        ("trig", "cos({a}*x)"),
        ("exponential", "{a}*exp(x)"),
        ("rational", "x/(x*x+{a})"),
        ("composition", "cos(x*x)+{a}"),
    ],
    "final": [
        ("polynomial", "{a}*x*x*x+{b}*x"),
        ("trig", "sin(x)+cos({a}*x)"),
        ("exponential", "exp(-x*x/{a})"),
        ("rational", "(x+{b})/(x*x+{a})"),
        ("composition", "sin(exp(x/{a}))"),
    ],
}


def generate(split="dev", seed=17, count=10, points=24):
    if split not in TEMPLATES or not 1 <= count <= 500 or not 2 <= points <= 1000:
        raise ValueError("invalid dataset configuration")
    salt = int.from_bytes(
        hashlib.sha256(f"{split}:{seed}".encode()).digest()[:8], "big"
    )
    rng = np.random.default_rng(salt)
    tasks = []
    seen = set()
    for i in range(count):
        family, template = TEMPLATES[split][i % 5]
        for _ in range(10000):
            expr = template.format(
                a=round(float(rng.uniform(0.5, 4)), 4),
                b=round(float(rng.uniform(-2, 2)), 4),
            )
            if expr not in seen:
                break
        else:
            raise ValueError("could not generate unique expressions")
        seen.add(expr)
        x = rng.uniform(-1, 1, points)
        held = np.concatenate([rng.uniform(-1, 1, points), rng.uniform(1, 2, points)])
        tasks.append(
            dict(
                id=hashlib.sha256(expr.encode()).hexdigest(),
                family=family,
                split=split,
                observations=dict(x=x.tolist(), y=evaluate(expr, x).tolist()),
                heldout=dict(x=held.tolist(), y=evaluate(expr, held).tolist()),
            )
        )
    return dict(schema=1, split=split, seed=seed, tasks=tasks)


def save_dataset(data, path):
    from pathlib import Path

    Path(path).write_text(json.dumps(data, indent=2))
